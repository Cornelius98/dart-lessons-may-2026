import 'dart:math';

void main(){

  //Arithmetic Operators: +, -, * (astrisk), /, %(modulus - remainder). pow(denominator, exponent)
  int a = 30;
  int b = 10;
  //int c = 40;

  //Addition: sum 
  int sum = a + b;
  print(sum); 

  //Substraction - finding difference
  int difference = a - b;
  print(difference);

  //Multiplication
  int product = a * b;
  print(product);

  //Division
  double quotient = a / b;
  print(quotient);

  //Modulus %
  int remainder = b % a;
  print(remainder);

  // 3 power 2
  num exponent = pow(3, 2);
  print(exponent);

}